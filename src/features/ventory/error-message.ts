/** Error messages safe to display in the UI; do not surface raw SQLite/file internals. */
export type ErrorArea = 'sale' | 'expense' | 'backup' | 'general';

const defaults: Record<ErrorArea, string> = {
  sale: 'Penjualan belum berhasil disimpan. Periksa stok lalu coba lagi.',
  expense: 'Pengeluaran belum berhasil diproses. Silakan coba kembali.',
  backup: 'Backup atau restore tidak berhasil. Pastikan file valid dan coba kembali.',
  general: 'Operasi gagal. Silakan coba kembali.',
};

export function toUserFacingMessage(error: unknown, area: ErrorArea = 'general'): string {
  const detail = error instanceof Error ? error.message : '';
  // Messages generated by Ventory's domain validation, not raw SQLite messages.
  if (/^(Keranjang masih kosong|Produk atau jumlah tidak valid|Produk ganda dalam keranjang|Ada produk yang sudah tidak tersedia|Total transaksi terlalu besar)\./.test(detail)) return detail;
  if (/^Stok .{1,160} (tidak cukup|berubah)\b/.test(detail)) return detail;
  if (/^(Kategori pengeluaran tidak valid|Nominal harus bilangan bulat|Keterangan maksimal 200 karakter|Tanggal harus valid|Pengeluaran tidak ditemukan|ID tidak valid)\./.test(detail)) return detail;
  if (/^Backup tidak valid: [^\r\n]{1,240}$/.test(detail)) return detail;
  if (/^(file terlalu besar|File JSON tidak dapat dibaca|file tidak ditemukan)\b/i.test(detail)) return detail;
  if (/SQLITE_BUSY|database is locked/i.test(detail)) {
    return 'Database sedang digunakan. Tunggu sebentar lalu ulangi.';
  }
  if (/UNIQUE constraint failed: products\.sku/i.test(detail)) {
    return 'SKU tersebut sudah digunakan oleh produk lain.';
  }
  return defaults[area];
}
